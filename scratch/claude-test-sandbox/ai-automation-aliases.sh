#!/usr/bin/env bash
# ==============================================================================
# PromptHub AI自動化コマンドエイリアス集
#
# 【導入手順】
# 1. お使いのシェルの設定ファイル（~/.zshrc または ~/.bashrc）を開く
# 2. 本ファイルの内容を末尾にコピー＆ペーストする
# 3. ターミナルで `source ~/.zshrc` を実行して設定を再読み込みする
# ==============================================================================

# 1. ステージされた変更差分からConventional Commitsメッセージを自動生成してコミット
alias gca="git add -A && claude 'ステージされた変更のConventional Commitメッセージを提案し、確認後にコミットを実行して'"

# 2. 直近の変更内容からPR（プルリクエスト）の概要文を作成
alias gpr="claude 'mainブランチとの差分を確認し、GitHubのPR用テンプレート（概要・変更点・動作確認手順）を作成して'"

# 3. 未整理メモ（memo.txt）を構造化議事録へ一発整形
alias ai-memo="claude 'プロジェクト内のメモファイルを読み込んで、決定事項とネクストアクション表付きのMarkdownに整形して'"

# 4. コードのリファクタリング＆型エラー修復
alias ai-fix="claude 'プロジェクトのビルドエラーやTypeScript型エラーを特定し、最小限の差分で自動修復して'"

echo "✨ PromptHub AI自動化エイリアスが読み込まれました！ (gca, gpr, ai-memo, ai-fix)"
